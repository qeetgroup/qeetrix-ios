import Foundation

/// `docs/token-values.json`: every generated token, where it came from, its
/// Swift name and its resolved value in every context it varies over — and every token that is not
/// generated, with the reason. Platform-neutral on purpose, so another platform's build of the same
/// tokens can be diffed against it token by token.
///
/// Units: lengths in points (1 CSS px, 1 rem = 16), durations in milliseconds, colours as the
/// package's OKLCH plus the encoded RGB this platform draws (0–1, in the colour space named).
struct TokenValuesReport {
    let model: TokenModel
    let provenance: Provenance

    static let path = "docs/token-values.json"

    func json() throws -> String {
        let package = try provenance.package(Provenance.tokensPackage)
        let base = model.source.defaultContext
        var tokens: [OrderedJSON] = []
        for token in model.included {
            let contexts: [(String, TokenContext)]
            switch token.variation {
            case .none: contexts = [("all", base)]
            case .colorScheme: contexts = model.source.colorSchemes.map { ($0, TokenContext(colorScheme: $0, density: base.density)) }
            case .density: contexts = model.source.densities.map { ($0, TokenContext(colorScheme: base.colorScheme, density: $0)) }
            }
            let values = try contexts.map { label, context in
                (label, try Self.value(token.value(context), dtcg: token.sources[context]!))
            }
            let source = token.sources[base]!
            tokens.append(
                .object(
                    [
                        ("path", .string(token.dotted)),
                        ("type", .string(source.type)),
                        ("swift", .string("\(token.group.swiftType).\(token.name)")),
                        ("css", .string(token.cssName)),
                        ("source", .string(source.file)),
                        ("alias", source.alias.map(OrderedJSON.string) ?? .null),
                        ("varies", .string(token.variation.rawValue)),
                        ("values", .object(values)),
                    ]))
        }
        return OrderedJSON.object([
            (
                "$comment",
                .string("GENERATED by qeetrix-gen from \(package.name) \(package.version) — do not edit. Run Scripts/generate.sh.")
            ),
            (
                "source",
                .object([
                    ("package", .string(package.name)),
                    ("version", .string(package.version)),
                    ("gitHead", .string(package.gitHead)),
                    ("integrity", .string(package.integrity)),
                    ("resolver", .string("dist/dtcg/qeetrix.resolver.json")),
                ])
            ),
            (
                "contexts",
                .object([
                    ("colorScheme", .array(model.source.colorSchemes.map(OrderedJSON.string))),
                    ("density", .array(model.source.densities.map(OrderedJSON.string))),
                ])
            ),
            (
                "units",
                .string(
                    "Lengths in points (1 CSS px = 1 pt, 1 rem = 16 pt); durations in ms; colours as the package's OKLCH and hex, and the encoded RGB iOS draws (0–1, in the named space)."
                )
            ),
            ("generated", .number(String(model.included.count))),
            ("tokens", .array(tokens)),
            (
                "excluded",
                .array(model.excluded.map { .object([("path", .string($0.dotted)), ("reason", .string($0.reason))]) })
            ),
        ]).serialized()
    }

    static func number(_ value: Double) -> OrderedJSON { .number(swiftNumber(value)) }

    static func color(_ color: ColorMath.EncodedColor, dtcg: OrderedJSON?) -> OrderedJSON {
        var pairs: [(String, OrderedJSON)] = []
        if let components = dtcg?["components"] { pairs.append(("oklch", components)) }
        pairs.append(("alpha", number(color.alpha)))
        if let hex = dtcg?["hex"] { pairs.append(("hex", hex)) }
        pairs.append(("space", .string(color.space.rawValue)))
        pairs.append(("rgb", .array([color.red, color.green, color.blue].map(number))))
        if color.gamutMapped { pairs.append(("gamutMapped", .bool(true))) }
        return .object(pairs)
    }

    static func value(_ value: TokenValue, dtcg: DTCGToken) throws -> OrderedJSON {
        switch value {
        case let .color(encoded): return color(encoded, dtcg: dtcg.value)
        case let .dimension(points): return .object([("points", number(points))])
        case let .number(number): return Self.number(number)
        case let .duration(seconds): return .object([("ms", number(seconds * 1000))])
        case let .easing(points): return .object([("cubicBezier", .array(points.map(number)))])
        case let .shadow(layers):
            let raw = dtcg.value.arrayValue ?? [dtcg.value]
            return .array(
                zip(layers, raw).map { layer, source in
                    .object([
                        ("x", number(layer.x)), ("y", number(layer.y)), ("blur", number(layer.blur)), ("spread", number(layer.spread)),
                        ("inset", .bool(layer.inset)), ("color", color(layer.color, dtcg: source["color"])),
                    ])
                })
        case let .typography(type):
            return .object([
                ("family", .string(type.family)), ("size", number(type.size)), ("weight", number(type.weight)),
                ("lineHeight", .number("\(type.lineHeight)")), ("lineHeightPoints", number(type.lineHeightLength)),
                ("letterSpacing", number(type.letterSpacing)), ("fontGeometry", .string(type.geometry)),
            ])
        }
    }
}
