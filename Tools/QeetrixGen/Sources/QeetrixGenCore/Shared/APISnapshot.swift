import Foundation

/// The library's public API as a sorted list of `<kind> <qualified name>` lines, read from the symbol
/// graphs `swift package dump-symbol-graph` writes. Committed as `api/Qeetrix.public-api.txt`;
/// a difference means the public API changed, which should be a decision, not a side effect.
///
/// Names carry argument labels (`QeetrixMotion.animation(_:_:reduceMotion:)`) but not types, so the
/// snapshot stays stable across compiler versions while still catching added, removed or renamed API.
/// Members a type only inherits from a protocol's default implementation are left out.
public enum APISnapshot {
    public static let path = "api/Qeetrix.public-api.txt"

    public static func render(symbolGraphs: [Data]) throws -> String {
        var lines: Set<String> = []
        for data in symbolGraphs {
            guard let graph = try JSONSerialization.jsonObject(with: data) as? [String: Any],
                let symbols = graph["symbols"] as? [[String: Any]]
            else { throw GeneratorError("A symbol graph is not in the expected format.") }
            for symbol in symbols {
                // Members a type only inherits (Equatable's !=, ShapeStyle's modifiers…) are synthesised.
                let precise = (symbol["identifier"] as? [String: Any])?["precise"] as? String ?? ""
                if precise.contains("::SYNTHESIZED::") { continue }
                guard let kind = (symbol["kind"] as? [String: Any])?["identifier"] as? String,
                    let path = symbol["pathComponents"] as? [String],
                    (symbol["accessLevel"] as? String).map({ $0 == "public" || $0 == "open" }) ?? false
                else { continue }
                lines.insert("\(kind.replacingOccurrences(of: "swift.", with: "")) \(path.joined(separator: "."))")
            }
        }
        guard !lines.isEmpty else { throw GeneratorError("The symbol graphs list no public symbols.") }
        return "# GENERATED by Scripts/api-check.sh --update — the public API of the Qeetrix module.\n"
            + lines.sorted().joined(separator: "\n") + "\n"
    }

    /// Every `Qeetrix*.symbols.json` under `directory`.
    public static func graphs(in directory: URL) throws -> [Data] {
        let names = try FileManager.default.contentsOfDirectory(atPath: directory.path)
            .filter { $0.hasPrefix("Qeetrix") && $0.hasSuffix(".symbols.json") }
            .sorted()
        return try names.map { try Data(contentsOf: directory.appendingPathComponent($0)) }
    }
}
