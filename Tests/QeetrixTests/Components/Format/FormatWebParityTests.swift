// The web's output for the same value and locale, case by case: `@qeetrix/react` 0.4.0's
// `formatNumber`, `formatCurrency`, `formatDate`, `formatDateTime` and `formatRelativeTime`
// (dist/format/format.js), the sizes its FileUpload writes, its date fields' all-number dates and
// ranges (internal/date.js) and RelativeTime's date past the threshold — their options and algorithms
// run on Node 24.15's `Intl` (ICU 78.2, CLDR 48), the engine of the web's server rendering, in 19
// locales. Dates are shown in Asia/Kolkata; relative times are against 2026-10-25T12:00:00Z.
//
// Every case where iOS writes what the web writes is here: 1,977 of 2,337. The rest differ because
// Apple's locale data differs from CLDR's — Latin digits for Bengali and Marathi, Indian grouping for
// Kannada and Malayalam, other month abbreviations and day periods — and are listed, one per locale
// and function, in `knownDifferences` below and on the Format page. English (India) and English (US)
// match in every case.

/// One call of a format function, in a locale, and what the web writes for it.
struct FormatParityCase: Sendable, CustomTestStringConvertible {
    enum Call: Sendable {
        case number(Double)
        case currency(String, String, wholeUnits: Bool)
        case percent(Double)
        case compact(Double)
        case fileSize(Int64)
        case date(String, QeetrixFormatDateStyle)
        case dateTime(String, QeetrixFormatDateStyle, QeetrixFormatTimeStyle)
        case relativeTime(seconds: Double)
        case numericDate(String)
        case dateRange(String, String)
        case abbreviatedDate(seconds: Int)
    }

    let call: Call
    let locale: String
    let web: String

    init(_ call: Call, _ locale: String, _ web: String) {
        self.call = call
        self.locale = locale
        self.web = web
    }

    var testDescription: String { "\(locale): \(call)" }

    /// The function's output on iOS.
    var ios: String { call.run(in: Locale(identifier: locale)) }
}

/// A case where Apple's locale data writes something other than CLDR's, with both.
struct FormatDataDifference: Sendable, CustomTestStringConvertible {
    let call: FormatParityCase.Call
    let locale: String
    let web: String
    let apple: String

    init(_ call: FormatParityCase.Call, _ locale: String, web: String, apple: String) {
        self.call = call
        self.locale = locale
        self.web = web
        self.apple = apple
    }

    var testDescription: String { "\(locale): \(call)" }
}

extension FormatParityCase.Call {
    static let now = Date(timeIntervalSince1970: 1_792_929_600)  // 2026-10-25T12:00:00Z
    static let kolkata = TimeZone(identifier: "Asia/Kolkata")!

    static func day(_ iso: String) -> DateComponents {
        let parts = iso.split(separator: "-").compactMap { Int($0) }
        return DateComponents(year: parts[0], month: parts[1], day: parts[2])
    }

    func run(in locale: Locale) -> String {
        switch self {
        case .number(let value):
            QeetrixFormat.number(value, locale: locale)
        case .currency(let amount, let code, let wholeUnits):
            QeetrixFormat.currency(Decimal(string: amount)!, code: code, fractionDigits: wholeUnits ? 0...0 : nil, locale: locale)
        case .percent(let fraction):
            QeetrixFormat.percent(fraction, locale: locale)
        case .compact(let value):
            QeetrixFormat.compactNumber(value, locale: locale)
        case .fileSize(let bytes):
            QeetrixFormat.fileSize(bytes, locale: locale)
        case .date(let iso, let style):
            QeetrixFormat.date(iso, style: style, locale: locale, timeZone: Self.kolkata)
        case .dateTime(let iso, let dateStyle, let timeStyle):
            QeetrixFormat.dateTime(iso, dateStyle: dateStyle, timeStyle: timeStyle, locale: locale, timeZone: Self.kolkata)
        case .relativeTime(let seconds):
            QeetrixFormat.relativeTime(Self.now.addingTimeInterval(seconds), now: Self.now, locale: locale)
        case .numericDate(let iso):
            QeetrixFormat.numericDate(Self.day(iso), locale: locale)
        case .dateRange(let start, let end):
            QeetrixFormat.dateRange(from: Self.day(start), to: Self.day(end), locale: locale)
        case .abbreviatedDate(let seconds):
            QeetrixFormat.abbreviatedDate(Date(timeIntervalSince1970: TimeInterval(seconds)), locale: locale, timeZone: Self.kolkata)
        }
    }
}

@Suite("Format: the web's output, case by case")
struct FormatWebParityTests {
    @Test("Numbers, as formatNumber", arguments: numberCases)
    func number(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Money, as formatCurrency", arguments: currencyCases)
    func currency(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Percentages, as formatNumber with style percent", arguments: percentCases)
    func percent(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Compact numbers, as formatNumber with notation compact", arguments: compactCases)
    func compact(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("File sizes, as FileUpload writes them", arguments: fileSizeCases)
    func fileSize(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Dates, as formatDate", arguments: dateCases)
    func date(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Dates and times, as formatDateTime", arguments: dateTimeCases)
    func dateTime(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("Relative times, as formatRelativeTime", arguments: relativeCases)
    func relativeTime(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("All-number dates and ranges, as the date fields write them", arguments: numericDateCases + dateRangeCases)
    func numericDate(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    @Test("RelativeTime's date past the threshold", arguments: abbreviatedCases)
    func abbreviatedDate(_ check: FormatParityCase) { #expect(check.ios == check.web) }

    /// When one of these fails because Apple's data now agrees with the web, move the case into the
    /// tables above and take it off the Format page's list of differences.
    @Test("Where Apple's locale data differs from CLDR's, iOS follows the system", arguments: knownDifferences)
    func appleLocaleData(_ difference: FormatDataDifference) {
        #expect(difference.apple != difference.web)
        #expect(difference.call.run(in: Locale(identifier: difference.locale)) == difference.apple)
    }
}

